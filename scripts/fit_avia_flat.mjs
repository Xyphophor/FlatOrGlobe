// Regenerates src/data/presets/avia-flat-fit.js (epic14): the best free
// layout of the airports on a plane (the flat model's steel-man, logic.fitFlat)
// for the flight times of src/data/presets/avia-flights.js. Stored because
// the multi-start search takes ~1 s -- too slow to redo at every mount on an
// old machine; the tab only replays the descent from the stored start.
// Run after `fog build avia-flights`; logic.test.js checks it is still
// the optimum. Usage: node scripts/fit_avia_flat.mjs
import { writeFileSync } from "node:fs";
import { ROUTES, AIRPORTS } from "../src/data/presets/avia-flights.js";
import { routeStats, fitTime, fitFlat } from "../src/tabs/avia/logic.js";

const stats = ROUTES.map((r) => routeStats(r, AIRPORTS));
const g = fitTime(stats, (s) => s.gc);
const f = fitFlat(stats, AIRPORTS, { ...g, starts: 60, iters: 800 });
const r = (x) => Math.round(x);
const out = { rms: Number(f.rms.toFixed(5)), keys: f.keys, init: f.init.map((p) => p.map(r)), pos: f.keys.map((k) => f.pos[k].map(r)), edges: f.edges, dof: f.dof };
writeFileSync(new URL("../src/data/presets/avia-flat-fit.js", import.meta.url),
  "// GENERATED by scripts/fit_avia_flat.mjs -- do not edit by hand (epic14).\n" +
  "// Best layout of the airports on a plane for the measured flight times (km), and the\n" +
  "// starting layout that leads to it (replayed by the tab's springs figure).\n" +
  `export const AVIA_FLAT_FIT = ${JSON.stringify(out)};\n`);
console.log(`flat rms ${(f.rms * 100).toFixed(2)} %, ${f.edges} routes, ${f.dof} free numbers`);
