// Regenerates src/data/presets/mag-obs-fit.js (epic12): the best-fit free
// parameters (fitted on I only) of the two flat layouts -- the globe is never fitted, on the measured inclinations of
// src/data/presets/mag-obs.js. Stored because the 2D search takes ~2 s --
// too slow to redo at every mount on an old machine. Run after
// `fog build mag-obs`; obs-logic.test.js checks it is still the optimum.
// Usage: node scripts/fit_mag_obs.mjs
import { writeFileSync } from "node:fs";
import { MAG_OBS } from "../src/data/presets/mag-obs.js";
import { analyse, fitFlat, fitFlat2Balanced, obsFromPreset } from "../src/tabs/mag/obs-logic.js";

const obs = obsFromPreset(MAG_OBS);
const rows = analyse(obs, { flat1: { d: 1 }, flat2: { d2: 1 } }).rows;
const fit = fitFlat(rows), bal = fitFlat2Balanced(rows);
const r = (x, n) => Number(x.toFixed(n));
const out = {
  flat1: { d: r(fit.flat1.d, 0), rms: r(fit.flat1.rms, 3) },
  flat2: { d2: r(fit.flat2.d2, 0), rms: r(fit.flat2.rms, 3) },
  flat2bal: { d2: r(bal.d2, 0), rms: r(bal.rms, 3) },
};
writeFileSync(new URL("../src/data/presets/mag-obs-fit.js", import.meta.url),
  "// GENERATED by scripts/fit_mag_obs.mjs -- do not edit by hand (epic12).\n" +
  "// Free parameters fitted (least squares on I only, degrees) to MAG_OBS.\n" +
  "// flat1.d = magnet depth, km; flat2.d2 = burial depth, km (ring = equal and opposite\n" +
  "// charge to the centre pole: net magnetic charge zero, div B = 0 -- 2026-09-30).\n" +
  "// flat2bal = flat2 fitted with both hemispheres weighted equally (quoted in the text only).\n" +
  `export const MAG_OBS_FIT = ${JSON.stringify(out, null, 2)};\n`);
console.log(JSON.stringify(out));
