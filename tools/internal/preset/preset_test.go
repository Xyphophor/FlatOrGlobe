package preset

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func setup(t *testing.T) (string, File) {
	t.Helper()
	root := t.TempDir()
	if err := os.MkdirAll(filepath.Join(root, "data"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(root, "data", "in.csv"), []byte("abc"), 0o644); err != nil {
		t.Fatal(err)
	}
	return root, File{
		Out: "src/data/presets/x.js", Command: "build x", Inputs: []string{"data/in.csv"},
		Notes: []string{"t = hours"}, Body: "export const X = 1;\n",
	}
}

func TestRenderHeader(t *testing.T) {
	root, f := setup(t)
	b, err := f.Render(root)
	if err != nil {
		t.Fatal(err)
	}
	want := "// GENERATED by `fog build x` (tools/) -- do not edit by hand.\n" +
		// sha256("abc")
		"// input data/in.csv sha256:ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad\n" +
		"// t = hours\nexport const X = 1;\n"
	if string(b) != want {
		t.Errorf("got\n%s\nwant\n%s", b, want)
	}
}

func TestRenderRejects(t *testing.T) {
	root, f := setup(t)
	f.Body = "no newline"
	if _, err := f.Render(root); err == nil {
		t.Error("body without final newline accepted")
	}
	_, f = setup(t)
	f.Notes = []string{"a\nb"}
	if _, err := f.Render(root); err == nil {
		t.Error("multi-line note accepted")
	}
	_, f = setup(t)
	f.Inputs = []string{"missing.csv"}
	if _, err := f.Render(root); err == nil {
		t.Error("missing input accepted")
	}
}

func TestWriteCycle(t *testing.T) {
	root, f := setup(t)
	if s, err := Write(root, f, true); err != nil || s != Stale {
		t.Fatalf("check on missing file: %v %v", s, err)
	}
	if _, err := os.Stat(filepath.Join(root, f.Out)); !os.IsNotExist(err) {
		t.Fatal("check mode wrote a file")
	}
	if s, err := Write(root, f, false); err != nil || s != Written {
		t.Fatalf("first write: %v %v", s, err)
	}
	if s, err := Write(root, f, false); err != nil || s != Unchanged {
		t.Fatalf("second write: %v %v", s, err)
	}
	if s, err := Write(root, f, true); err != nil || s != Unchanged {
		t.Fatalf("check after write: %v %v", s, err)
	}
	// an input change makes the preset stale through its hash alone
	if err := os.WriteFile(filepath.Join(root, "data", "in.csv"), []byte("abd"), 0o644); err != nil {
		t.Fatal(err)
	}
	if s, _ := Write(root, f, true); s != Stale {
		t.Fatalf("input changed, check says %v", s)
	}
	entries, _ := os.ReadDir(filepath.Join(root, "src/data/presets"))
	for _, e := range entries {
		if strings.HasPrefix(e.Name(), ".fog-") {
			t.Errorf("temporary file left: %s", e.Name())
		}
	}
}
