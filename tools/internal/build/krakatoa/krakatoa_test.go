func TestAngle(t *testing.T) {
	cases := []struct {
		in   string
		want float64
		ok   bool
	}{
		{"6 9 S", -6.15, true}, {"105 22 E", 105.3667, true}, {"37 50 S", -37.8333, true},
		{"36 6 W", -36.1, true}, {"59 41 N", 59.6833, true}, {"", 0, false},
	}
	for _, c := range cases {
		v, ok, err := Angle(c.in)
		if err != nil || ok != c.ok || v != c.want {
			t.Errorf("Angle(%q) = %v %v %v, want %v %v", c.in, v, ok, err, c.want, c.ok)
		}
	}
	for _, bad := range []string{"6 9", "6 x S", "6 9 Q", "6.5 9 N"} {
		if _, _, err := Angle(bad); err == nil {
			t.Errorf("Angle(%q) accepted", bad)
		}
	}
}

func TestHM(t *testing.T) {
	cases := []struct {
		in    string
		kind  Kind
		h     float64
		flags string
	}{
		{"", None, 0, ""}, {"  ", None, 0, ""}, {"?", Query, 0, ""},
		{"12:51", Value, 12 + 51.0/60, ""}, {"12:51*", Value, 12 + 51.0/60, "*"},
		{"8:14?", Value, 8 + 14.0/60, "?"}, {"34:25+", Value, 34 + 25.0/60, "+"},
		{"-0:42", Value, -42.0 / 60, ""}, {" 17:10 ", Value, 17 + 10.0/60, ""},
	}
	for _, c := range cases {
		got, err := HM(c.in)
		if err != nil || got.Kind != c.kind || got.H != c.h || got.Flags != c.flags {
			t.Errorf("HM(%q) = %+v %v", c.in, got, err)
		}
	}
	for _, bad := range []string{"12", "12:5:1", "a:10", "12:b"} {
		if _, err := HM(bad); err == nil {
			t.Errorf("HM(%q) accepted", bad)
		}
	}
}

func realRoot(t *testing.T) string {
	t.Helper()
	root, err := repo.Find(".")
	if err != nil {
		t.Fatal(err)
	}
	return root
}

// Parity with the Python oracle: testdata/seis-krakatoa.python.js is the
// file scripts/build_krakatoa.py wrote on 2026-10-14 (identical to the
// committed preset). Below the header, the Go output must be the same
// bytes; the header differs only by the generator line and input hashes.
func TestParityWithPython(t *testing.T) {
	root := realRoot(t)
	res, err := Compute(root)
	if err != nil {
		t.Fatal(err)
	}
	if len(res.Bad) != 0 {
		t.Fatalf("transcription mismatch: %v", res.Bad)
	}
	// what the Python script printed: "47 stations, 175 intervals checked"
	if len(res.Stations) != 47 || res.Checked != 175 {
		t.Errorf("%d stations, %d intervals; Python had 47 and 175", len(res.Stations), res.Checked)
	}
	got, err := res.File().Render(root)
	if err != nil {
		t.Fatal(err)
	}
	want, err := os.ReadFile("testdata/seis-krakatoa.python.js")
	if err != nil {
		t.Fatal(err)
	}
	gl := strings.SplitAfter(string(got), "\n")
	wl := strings.SplitAfter(string(want), "\n")
	if !strings.HasPrefix(gl[0], "// GENERATED by `fog build krakatoa`") ||
		!strings.HasPrefix(gl[1], "// input "+Stations+" sha256:") ||
		!strings.HasPrefix(gl[2], "// input "+Table8+" sha256:") {
		t.Fatalf("header:\n%s%s%s", gl[0], gl[1], gl[2])
	}
	g, w := strings.Join(gl[3:], ""), strings.Join(wl[1:], "")
	if g != w {
		gs, ws := strings.Split(g, "\n"), strings.Split(w, "\n")
		for i := range min(len(gs), len(ws)) {
			if gs[i] != ws[i] {
				t.Fatalf("first difference at body line %d:\n go: %s\n py: %s", i+1, gs[i], ws[i])
			}
		}
		t.Fatalf("length differs: %d vs %d lines", len(gs), len(ws))
	}
}

// A transcription error in either table must stop the build.
func TestMismatchIsReported(t *testing.T) {
	root := realRoot(t)
	tmp := t.TempDir()
	dir := filepath.Join(tmp, Dir)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		t.Fatal(err)
	}
	st, _ := os.ReadFile(filepath.Join(root, Stations))
	t8, _ := os.ReadFile(filepath.Join(root, Table8))
	// Pawlowsk I-II is 17:10 in Table VIII; make it 17:12
	bad := strings.Replace(string(t8), "Pawlowsk,17:10,", "Pawlowsk,17:12,", 1)
	if bad == string(t8) {
		t.Fatal("fixture: Pawlowsk row not found")
	}
	os.WriteFile(filepath.Join(tmp, Stations), st, 0o644)
	os.WriteFile(filepath.Join(tmp, Table8), []byte(bad), 0o644)
	res, err := Compute(tmp)
	if err != nil {
		t.Fatal(err)
	}
	if len(res.Bad) != 1 || !strings.Contains(res.Bad[0], "Pawlowsk I-II") || !strings.Contains(res.Bad[0], "Table VIII 1032 min") {
		t.Fatalf("Bad = %v", res.Bad)
	}
}

func TestMissingVent(t *testing.T) {
	tmp := t.TempDir()
	os.MkdirAll(filepath.Join(tmp, Dir), 0o755)
	os.WriteFile(filepath.Join(tmp, Stations), []byte("station,lat,lon,I,II,III,IV,V,VI,VII\nX,1 0 N,2 0 E,1:00,,,,,,\n"), 0o644)
	os.WriteFile(filepath.Join(tmp, Table8), []byte("station,I-II\n"), 0o644)
	if _, err := Compute(tmp); err == nil || !strings.Contains(err.Error(), "no Krakatoa row") {
		t.Fatalf("err = %v", err)
	}
}
