package parity

import (
	"strings"
	"testing"
)

func TestCompare(t *testing.T) {
	py := "// GENERATED by python\n// note\nexport const X = [1.2345, -0.5, 7, \"a 1.5\"];\n"
	same := "// GENERATED by fog\n// input x\n// note\nexport const X = [1.2345, -0.5, 7, \"a 1.5\"];\n"
	if f, err := Compare(same, py); err != nil || len(f) != 0 {
		t.Fatalf("identical bodies: %v %v", f, err)
	}
	flip := strings.Replace(same, "1.2345", "1.2346", 1)
	f, err := Compare(flip, py)
	if err != nil || len(f) != 1 || f[0].Go != "1.2346" || f[0].Py != "1.2345" || f[0].Line != 1 {
		t.Fatalf("one flip: %v %v", f, err)
	}
	for _, bad := range []string{
		strings.Replace(same, "1.2345", "1.2347", 1), // two units
		strings.Replace(same, "1.2345", "1.234", 1),  // other precision
		strings.Replace(same, "-0.5", "0.5", 1),      // sign
		strings.Replace(same, "const X", "const Y", 1),
		same + "extra\n",
	} {
		if _, err := Compare(bad, py); err == nil {
			t.Errorf("accepted:\n%s", bad)
		}
	}
	// carry across digits: 0.9999 -> 1.0000 is one unit
	if !oneUnit("0.9999", "1.0000") || !oneUnit("-0.0001", "0.0000") || oneUnit("1e5", "1e5") {
		t.Error("oneUnit carry/sign/exponent")
	}
}

func TestBody(t *testing.T) {
	if Body("// a\n// b\nx\n// c\n") != "x\n// c\n" {
		t.Error("only the leading comment block is dropped")
	}
	if Body("// only\n") != "" || Body("// no newline") != "" {
		t.Error("all-comment input")
	}
}
